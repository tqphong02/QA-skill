import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  moduleArtifactPaths,
  resolveModuleIdentity,
} from '../assets/templates/scripts/artifact-naming.mjs';
import { verifyAutomationComplexity } from '../assets/templates/scripts/verify-automation-complexity.mjs';
import { verifyModuleArtifactLayout } from '../assets/templates/scripts/verify-module-artifact-layout.mjs';

const GENERATED = '// @generated by scripts/generate-pom-code.mjs; do not edit\n';

function write(root, relativePath, content) {
  const filePath = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  return filePath;
}

test('domain/feature identity produces nested module source and test paths', () => {
  const identity = resolveModuleIdentity({
    group: 'Checkout',
    domain: 'Commerce',
    feature: 'Guest Checkout',
  });
  assert.deepEqual(identity, {
    group: 'Checkout',
    domain: 'commerce',
    feature: 'guest-checkout',
    key: 'commerce/guest-checkout',
    slug: 'commerce-guest-checkout',
  });
  const paths = moduleArtifactPaths('project', identity, 'functional', ['ui', 'api']);
  assert.equal(paths.page, path.join('project', 'src/modules/commerce/guest-checkout/ui/guest-checkout.page.ts'));
  assert.equal(paths.client, path.join('project', 'src/modules/commerce/guest-checkout/api/guest-checkout.client.ts'));
  assert.equal(paths.spec, path.join('project', 'tests/functional/commerce/guest-checkout.functional.spec.ts'));
});

test('complexity gate blocks route, selector, action, operation and file growth above config', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'automation-complexity-'));
  try {
    const planPath = write(root, 'plans/checkout.json', JSON.stringify({
      schema_version: 1,
      module: { group: 'Checkout', domain: 'commerce', feature: 'checkout' },
      testcases: [{
        testcase_id: 'CHECKOUT-01',
        entry: { route: '/cart' },
        outcome_route: '/done',
        selector_target_keys: ['buy_button', 'total'],
        selector_target_routes: { buy_button: '/cart', total: '/cart' },
        steps: [{ required_method: 'buy' }, { required_method: 'review' }],
        api: { method: 'POST', endpoint: '/orders', body: {}, expected_status: 201, expected_body: {} },
      }],
    }));
    const configPath = write(root, 'automation-complexity.json', JSON.stringify({
      schema_version: 1,
      limits: {
        routes_per_module: 1,
        selectors_per_module: 1,
        actions_per_page: 1,
        api_operations_per_client: 1,
        schema_variants_per_operation: 1,
        lines_per_generated_file: 10,
      },
    }));
    const result = verifyAutomationComplexity({ planPaths: [planPath], projectRoot: root, configPath });
    assert.equal(result.status, 'BLOCKED');
    assert.ok(result.violations.some(item => item.metric === 'routes_per_module'));
    assert.ok(result.violations.some(item => item.metric === 'selectors_per_module'));
    assert.ok(result.violations.some(item => item.metric === 'actions_per_page'));
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test('layout verifier accepts owned shared components and blocks unowned manual extensions', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'automation-ownership-'));
  try {
    const identity = resolveModuleIdentity({ group: 'Checkout', domain: 'commerce', feature: 'checkout' });
    const paths = moduleArtifactPaths(root, identity, 'ui', ['ui']);
    const manifestPath = write(root, 'checkout.automation.json', JSON.stringify({
      schema_version: 1,
      testcases: [{
        testcase_id: 'CHECKOUT-UI-01', group: 'Checkout', domain: 'commerce', feature: 'checkout',
        execution: { steps: [{ action: 'click' }] },
      }],
    }));
    write(root, path.relative(root, paths.selector), `${GENERATED}export const selectors = {};\n`);
    write(root, path.relative(root, paths.page), `${GENERATED}export class CheckoutPage {}\n`);
    write(root, path.relative(root, paths.spec), `${GENERATED}test('CHECKOUT-UI-01 | happy', () => {});\n`);
    write(root, 'src/shared/components/header.component.ts', 'export class HeaderComponent {}\n');
    write(root, 'src/shared/ownership.json', JSON.stringify({
      schema_version: 1,
      extensions: [{
        path: 'src/shared/components/header.component.ts',
        kind: 'component',
        owner: 'checkout-team',
        purpose: 'Reusable application header',
      }],
    }));
    const pass = verifyModuleArtifactLayout({ manifestPath, projectRoot: root, surface: 'ui' });
    assert.equal(pass.status, 'PASS', JSON.stringify(pass.violations));

    write(root, 'src/modules/commerce/checkout/extensions/manual.helper.ts', 'export const manual = true;\n');
    const blocked = verifyModuleArtifactLayout({ manifestPath, projectRoot: root, surface: 'ui' });
    assert.equal(blocked.status, 'FAILED');
    assert.ok(blocked.violations.some(item => item.code === 'MANUAL_EXTENSION_UNOWNED'));
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
