#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  moduleArtifactNames,
  moduleArtifactPaths,
  moduleOperationInventoryPath,
  moduleSchemaRoot,
  normalizeCapabilities,
  normalizeSurface,
  RESERVED_MODULE_SLUGS,
  resolveModuleIdentity,
  resolveModuleSlug,
} from './artifact-naming.mjs';

const GENERATED_MARKER = '// @generated by scripts/generate-pom-code.mjs; do not edit';
const OWNERSHIP_FILE = path.join('src', 'shared', 'ownership.json');
const OWNERSHIP_KINDS = new Set(['component', 'helper', 'schema', 'adapter', 'extension']);

function getArg(flag, fallback = '') {
  const index = process.argv.indexOf(flag);
  return index === -1 ? fallback : process.argv[index + 1] || fallback;
}

function getArgs(flag) {
  const values = [];
  for (let index = 0; index < process.argv.length; index += 1) {
    if (process.argv[index] === flag && process.argv[index + 1]) values.push(process.argv[index + 1]);
  }
  return values;
}

function uniqueStrings(values) {
  return [...new Set((values || []).flatMap(value => String(value || '').split(','))
    .map(value => value.trim()).filter(Boolean))];
}

function testDeclarations(source) {
  return [...source.matchAll(/\btest\s*\(\s*(["'])(.*?)\1/g)]
    .map(match => match[2].split('|')[0].trim()).filter(Boolean);
}

function inferredTestcaseCapabilities(testcase, surface = 'functional') {
  const normalizedSurface = normalizeSurface(surface);
  const explicit = Array.isArray(testcase?.capabilities)
    ? testcase.capabilities : testcase?.capability ? [testcase.capability] : [];
  const inferred = [
    ...explicit,
    ...(testcase?.api && typeof testcase.api === 'object' ? ['api'] : []),
    ...(testcase?.execution && typeof testcase.execution === 'object' ? ['ui'] : []),
    ...(String(testcase?.section_kind || '').toLowerCase() === 'api' ? ['api'] : []),
  ].map(value => String(value || '').toLowerCase());
  const unique = ['ui', 'api'].filter(capability => inferred.includes(capability));
  if (unique.length) return unique;
  return normalizedSurface === 'api' ? ['api'] : ['ui'];
}

function testcaseBelongsToSurface(testcase, surface) {
  const normalized = normalizeSurface(surface);
  return normalized === 'functional' || inferredTestcaseCapabilities(testcase, normalized).includes(normalized);
}

function testcaseScopeFromPlans(planPaths) {
  if (!planPaths?.length) return [];
  const records = planPaths.map(input => {
    const planPath = path.resolve(input);
    const plan = JSON.parse(fs.readFileSync(planPath, 'utf8'));
    if (plan.schema_version !== 1 || !Array.isArray(plan.testcases)
      || plan.testcases.length < 1 || plan.testcases.length > 20
      || !plan.module || !Array.isArray(plan.modules) || plan.modules.length !== 1) {
      throw new Error(`Invalid bounded pom-plan: ${planPath}`);
    }
    return { plan, planPath };
  });
  const owner = resolveModuleIdentity(records[0].plan.module);
  for (const { plan, planPath } of records) {
    if (resolveModuleIdentity(plan.module).key !== owner.key) {
      throw new Error(`All scoped pom-plans must belong to one module: ${planPath}`);
    }
  }
  const cases = records.flatMap(({ plan }) => plan.testcases);
  if (records.length > 1 && cases.some(testcase => !Number.isInteger(testcase.source_index))) {
    throw new Error('Batched pom-plans require source_index on every testcase');
  }
  cases.sort((left, right) => (left.source_index ?? 0) - (right.source_index ?? 0));
  const ids = cases.map(testcase => String(testcase.testcase_id || '').trim());
  if (ids.some(id => !id) || new Set(ids).size !== ids.length) {
    throw new Error('Scoped pom-plans require unique testcase IDs');
  }
  return ids;
}

function walkFiles(root, predicate = () => true) {
  if (!fs.existsSync(root)) return [];
  const files = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const filePath = path.join(root, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(filePath, predicate));
    else if (entry.isFile() && predicate(filePath)) files.push(path.resolve(filePath));
  }
  return files;
}

function portable(projectRoot, filePath) {
  return path.relative(projectRoot, filePath).replaceAll('\\', '/');
}

function ownershipAllowed(relativePath) {
  return /^src\/shared\/(?:components|extensions|helpers|schemas)\/.+\.ts$/.test(relativePath)
    || /^src\/modules\/[^/]+\/[^/]+\/extensions\/.+\.ts$/.test(relativePath);
}

function verifyOwnership(projectRoot, violations) {
  const registryPath = path.join(projectRoot, OWNERSHIP_FILE);
  const manualFiles = [
    ...walkFiles(path.join(projectRoot, 'src', 'shared'), file => file.endsWith('.ts')),
    ...walkFiles(path.join(projectRoot, 'src', 'modules'), file => /[\\/]extensions[\\/].+\.ts$/.test(file)),
  ];
  let registry = { schema_version: 1, extensions: [] };
  if (fs.existsSync(registryPath)) {
    try { registry = JSON.parse(fs.readFileSync(registryPath, 'utf8')); } catch (error) {
      violations.push({ code: 'OWNERSHIP_REGISTRY_INVALID_JSON', file: registryPath, message: error.message });
      return new Set();
    }
  } else if (manualFiles.length > 0) violations.push({ code: 'OWNERSHIP_REGISTRY_MISSING', file: registryPath });
  if (registry.schema_version !== 1 || !Array.isArray(registry.extensions)) {
    violations.push({ code: 'OWNERSHIP_REGISTRY_SCHEMA_INVALID', file: registryPath });
    return new Set();
  }
  const owned = new Set();
  for (const [index, entry] of registry.extensions.entries()) {
    const relativePath = String(entry?.path || '').replaceAll('\\', '/').replace(/^\.\//, '');
    const absolutePath = path.resolve(projectRoot, relativePath);
    if (!relativePath || !ownershipAllowed(relativePath) || path.relative(projectRoot, absolutePath).startsWith('..')) {
      violations.push({ code: 'OWNERSHIP_PATH_INVALID', index, path: relativePath });
      continue;
    }
    if (owned.has(absolutePath)) {
      violations.push({ code: 'OWNERSHIP_DUPLICATE_PATH', path: relativePath });
      continue;
    }
    owned.add(absolutePath);
    if (!String(entry.owner || '').trim() || !String(entry.purpose || '').trim()
      || !OWNERSHIP_KINDS.has(String(entry.kind || ''))) {
      violations.push({ code: 'OWNERSHIP_METADATA_INCOMPLETE', path: relativePath });
    }
    if (!fs.existsSync(absolutePath) || !fs.statSync(absolutePath).isFile()) {
      violations.push({ code: 'OWNERSHIP_TARGET_MISSING', path: relativePath });
    } else {
      const canonicalRoot = fs.realpathSync.native(projectRoot);
      const canonicalTarget = fs.realpathSync.native(absolutePath);
      const canonicalRelative = path.relative(canonicalRoot, canonicalTarget);
      if (canonicalRelative.startsWith('..') || path.isAbsolute(canonicalRelative)) {
        violations.push({ code: 'OWNERSHIP_TARGET_SYMLINK_ESCAPE', path: relativePath });
      } else if (fs.readFileSync(absolutePath, 'utf8').startsWith(GENERATED_MARKER)) {
        violations.push({ code: 'OWNERSHIP_TARGET_IS_GENERATED', path: relativePath });
      }
    }
  }
  for (const filePath of manualFiles) {
    if (!owned.has(filePath)) violations.push({ code: 'MANUAL_EXTENSION_UNOWNED', file: portable(projectRoot, filePath) });
  }
  return owned;
}

function inventorySchemaFiles(projectRoot, identity, violations) {
  const inventoryPath = moduleOperationInventoryPath(projectRoot, identity);
  if (!fs.existsSync(inventoryPath)) {
    violations.push({ code: 'API_OPERATION_INVENTORY_MISSING', file: inventoryPath });
    return [];
  }
  let inventory;
  try { inventory = JSON.parse(fs.readFileSync(inventoryPath, 'utf8')); } catch (error) {
    violations.push({ code: 'API_OPERATION_INVENTORY_INVALID', file: inventoryPath, message: error.message });
    return [];
  }
  const schemaRoot = path.resolve(moduleSchemaRoot(projectRoot, identity));
  const files = [];
  for (const operation of inventory.operations || []) {
    const source = String(operation?.schemas?.source || '');
    const filePath = path.resolve(projectRoot, source);
    if (!source || (filePath !== schemaRoot && !filePath.startsWith(`${schemaRoot}${path.sep}`))) {
      violations.push({ code: 'API_SCHEMA_SOURCE_OUTSIDE_MODULE', source });
      continue;
    }
    files.push(filePath);
  }
  return [...new Set(files)];
}

function verifyModuleArtifactLayout({ manifestPath, projectRoot, surface = 'functional', testcaseIds = [], planPaths = [] }) {
  const normalizedSurface = normalizeSurface(surface);
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (manifest.schema_version !== 1 || !Array.isArray(manifest.testcases)) {
    throw new Error('automation manifest must use schema_version=1 and contain testcases[]');
  }
  const planIds = testcaseScopeFromPlans(planPaths);
  const explicitIds = uniqueStrings(testcaseIds);
  if (planIds.length && explicitIds.length && JSON.stringify(planIds) !== JSON.stringify(explicitIds)) {
    throw new Error('Explicit testcaseIds do not match the scoped pom-plan testcase order');
  }
  const scopedIds = planIds.length ? planIds : explicitIds;
  const scopedSet = new Set(scopedIds);
  const selected = manifest.testcases.filter(testcase => testcaseBelongsToSurface(testcase, normalizedSurface)
    && (!scopedSet.size || scopedSet.has(String(testcase.testcase_id || '').trim())));
  const violations = [];
  const manifestIds = manifest.testcases.map(item => String(item.testcase_id || '').trim());
  const duplicateManifestIds = manifestIds.filter((id, index) => id && manifestIds.indexOf(id) !== index);
  if (duplicateManifestIds.length) violations.push({ code: 'DUPLICATE_MANIFEST_TESTCASE_ID', testcase_ids: [...new Set(duplicateManifestIds)] });
  const unknown = scopedIds.filter(id => !manifestIds.includes(id));
  if (unknown.length) violations.push({ code: 'TESTCASE_SCOPE_ID_UNKNOWN', testcase_ids: unknown });
  if (!selected.length) violations.push({ code: 'NO_TESTCASES_FOR_SURFACE', surface: normalizedSurface });

  const modules = new Map();
  for (const testcase of selected) {
    const testcaseId = String(testcase.testcase_id || '').trim();
    if (!testcaseId) throw new Error('Every testcase must have testcase_id');
    const identity = resolveModuleIdentity(testcase);
    if (!modules.has(identity.key)) modules.set(identity.key, { identity, testcaseIds: [], capabilities: [] });
    const record = modules.get(identity.key);
    if (record.identity.group !== identity.group) {
      violations.push({
        code: 'MODULE_IDENTITY_COLLISION',
        key: identity.key,
        modules: [record.identity.group, identity.group],
      });
    }
    record.testcaseIds.push(testcaseId);
    for (const capability of inferredTestcaseCapabilities(testcase, normalizedSurface)) {
      if (!record.capabilities.includes(capability)) record.capabilities.push(capability);
    }
  }
  if (normalizedSurface === 'functional') {
    const invalid = selected.filter(testcase => {
      const caps = inferredTestcaseCapabilities(testcase, normalizedSurface);
      const order = (testcase.capability_order || []).map(value => String(value).toLowerCase());
      return caps.length !== 2 || order.length !== 2 || !order.includes('ui') || !order.includes('api');
    });
    if (invalid.length) violations.push({ code: 'FUNCTIONAL_FLOW_NOT_COMPOSED', testcase_ids: invalid.map(item => item.testcase_id) });
  }

  const ownedManualFiles = verifyOwnership(projectRoot, violations);
  const expectedFiles = new Set();
  const mappedIds = [];
  const artifacts = [];
  for (const { identity, testcaseIds: expectedIds, capabilities: rawCapabilities } of modules.values()) {
    const capabilities = normalizeCapabilities(normalizedSurface, rawCapabilities);
    if (RESERVED_MODULE_SLUGS.has(identity.domain) || RESERVED_MODULE_SLUGS.has(identity.feature)) {
      violations.push({ code: 'MODULE_SLUG_RESERVED', module: identity.key });
    }
    const expected = moduleArtifactPaths(projectRoot, identity, normalizedSurface, capabilities);
    const names = moduleArtifactNames(identity, normalizedSurface, capabilities);
    const schemaFiles = capabilities.includes('api') ? inventorySchemaFiles(projectRoot, identity, violations) : [];
    for (const filePath of [...Object.values(expected), ...schemaFiles]) expectedFiles.add(path.resolve(filePath));
    artifacts.push({ module: identity.group, ...identity, capabilities, names, schema_files: schemaFiles, ...expected });
    for (const [kind, filePath] of Object.entries(expected)) {
      if (!fs.existsSync(filePath)) violations.push({ code: 'MODULE_ARTIFACT_MISSING', module: identity.key, kind, file: filePath });
    }
    for (const filePath of schemaFiles) {
      if (!fs.existsSync(filePath)) violations.push({ code: 'MODULE_ARTIFACT_MISSING', module: identity.key, kind: 'schema', file: filePath });
    }
    if (fs.existsSync(expected.spec)) {
      const actualIds = testDeclarations(fs.readFileSync(expected.spec, 'utf8'));
      mappedIds.push(...actualIds);
      if (JSON.stringify(actualIds) !== JSON.stringify(expectedIds)) {
        violations.push({ code: 'MODULE_TESTCASE_ORDER_MISMATCH', module: identity.key, expected_ids: expectedIds, actual_ids: actualIds });
      }
    }
  }

  const generatedCandidates = [
    ...walkFiles(path.join(projectRoot, 'src', 'modules'), file => file.endsWith('.ts')),
    ...walkFiles(path.join(projectRoot, 'tests', normalizedSurface), file => file.endsWith('.spec.ts')),
  ];
  for (const filePath of generatedCandidates) {
    if (ownedManualFiles.has(filePath)) continue;
    if (scopedIds.length && ![...modules.values()].some(({ identity }) => (
      filePath.includes(`${path.sep}${identity.domain}${path.sep}${identity.feature}${path.sep}`)
      || filePath.endsWith(`${path.sep}${identity.feature}.${normalizedSurface}.spec.ts`)
    ))) continue;
    const source = fs.readFileSync(filePath, 'utf8');
    if (/\.batch-\d+/i.test(filePath)) violations.push({ code: 'BATCH_LEAKED_TO_FINAL_CODE', file: filePath });
    if (!expectedFiles.has(filePath)) violations.push({ code: 'UNMAPPED_FINAL_MODULE_ARTIFACT', file: filePath });
    if (expectedFiles.has(filePath) && !source.startsWith(GENERATED_MARKER)) {
      violations.push({ code: 'GENERATED_ARTIFACT_MARKER_MISSING', file: filePath });
    }
  }

  const expectedAllIds = selected.map(testcase => String(testcase.testcase_id));
  const duplicates = mappedIds.filter((id, index) => mappedIds.indexOf(id) !== index);
  const missing = expectedAllIds.filter(id => !mappedIds.includes(id));
  const extra = mappedIds.filter(id => !expectedAllIds.includes(id));
  if (duplicates.length) violations.push({ code: 'DUPLICATE_TESTCASE_ID', testcase_ids: [...new Set(duplicates)] });
  if (missing.length) violations.push({ code: 'MISSING_TESTCASE_ID', testcase_ids: missing });
  if (extra.length) violations.push({ code: 'EXTRA_TESTCASE_ID', testcase_ids: extra });
  return {
    status: violations.length ? 'FAILED' : 'PASS',
    module_count: modules.size,
    testcase_count: expectedAllIds.length,
    mapped_testcase_count: mappedIds.length,
    surface: normalizedSurface,
    scope: scopedIds.length ? 'selected' : 'full',
    scoped_testcase_ids: scopedIds,
    ownership_registry: OWNERSHIP_FILE.replaceAll('\\', '/'),
    artifacts,
    violations,
  };
}

function main() {
  const manifestArg = getArg('--manifest');
  if (!manifestArg) throw new Error('BLOCKED: --manifest is required');
  const projectRoot = path.resolve(getArg('--project-root', '.'));
  const result = verifyModuleArtifactLayout({
    manifestPath: path.resolve(manifestArg), projectRoot,
    surface: getArg('--surface', 'functional'),
    testcaseIds: getArgs('--testcase-id').flatMap(value => value.split(',')),
    planPaths: getArgs('--plan'),
  });
  const outputArg = getArg('--output');
  if (outputArg) {
    const outputPath = path.resolve(outputArg);
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, `${JSON.stringify(result, null, 2)}\n`, 'utf8');
  }
  console.log(JSON.stringify(result, null, 2));
  if (result.status !== 'PASS') process.exitCode = 1;
}

