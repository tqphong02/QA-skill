#!/usr/bin/env python3
"""
gen-gherkin.py — Generate Gherkin .feature files from testcase JSON source
Usage: python scripts/gen-gherkin.py <input.json> <output.feature>

Trigger: user requests "Feature file", "Given/When/Then", "Gherkin", "Cucumber"
Maps SCN-* scenarios → Feature/Scenario/Scenario Outline preserving testcase_id
"""
import argparse
import json
import re
import sys
from pathlib import Path


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
OUTLINE_TECHNIQUES = {"BVA", "Pairwise", "Decision Table", "Combinatorial Testing", "Domain Testing"}
VALID_TECHNIQUES = {
    "EP", "BVA", "Decision Table", "State Transition",
    "Use Case Testing", "Error Guessing", "Pairwise",
}


# ---------------------------------------------------------------------------
# Validators
# ---------------------------------------------------------------------------
def validate_case(case: dict, scenario_id: str) -> list[str]:
    errors = []
    if not case.get("expected_result") and not case.get("execution", {}).get("expected"):
        errors.append(f"{scenario_id}/{case.get('testcase_id','?')}: missing expected_result")
    return errors


def validate_scenario(scenario: dict) -> list[str]:
    errors = []
    for case in scenario.get("cases", []):
        errors.extend(validate_case(case, scenario.get("id", "?")))
    return errors


# ---------------------------------------------------------------------------
# Gherkin renderers
# ---------------------------------------------------------------------------
def _sanitize(text: str) -> str:
    return re.sub(r"\s+", " ", str(text)).strip()


def render_scenario(scenario: dict) -> str:
    lines = []
    scn_id = scenario.get("id", "SCN-???")
    name = _sanitize(scenario.get("name", "unnamed scenario"))
    cases = scenario.get("cases", [])
    technique = (cases[0].get("bb_technique", "") if cases else "").strip()

    if technique in OUTLINE_TECHNIQUES and len(cases) > 1:
        # Scenario Outline with Examples table
        lines.append(f"  # {scn_id}")
        lines.append(f"  Scenario Outline: {name}")

        # Build generic Given/When/Then from first case as template
        first = cases[0]
        preconditions = first.get("preconditions", [])
        if preconditions:
            for i, pre in enumerate(preconditions):
                kw = "Given" if i == 0 else "And"
                lines.append(f"    {kw} {_sanitize(pre)}")
        else:
            lines.append(f"    Given the system is in a valid state")

        action = first.get("action_summary") or first.get("description", "the user performs the action")
        lines.append(f"    When {_sanitize(action)}")

        lines.append(f"    Then the result should be <expected_result>")
        lines.append("")

        # Examples table
        lines.append("    Examples:")
        lines.append("      | testcase_id | input | expected_result |")
        for case in cases:
            tc_id = case.get("testcase_id", "?")
            inp = _sanitize(str(case.get("input", case.get("test_data", ""))))
            exp = _sanitize(str(
                case.get("expected_result") or
                case.get("execution", {}).get("expected", "")
            ))
            lines.append(f"      | {tc_id} | {inp} | {exp} |")
    else:
        # Individual Scenario per case
        for case in cases:
            tc_id = case.get("testcase_id", "?")
            case_name = _sanitize(case.get("description", name))
            lines.append(f"  # {scn_id} / {tc_id}")
            lines.append(f"  Scenario: {case_name}")

            preconditions = case.get("preconditions", [])
            if preconditions:
                for i, pre in enumerate(preconditions):
                    kw = "Given" if i == 0 else "And"
                    lines.append(f"    {kw} {_sanitize(pre)}")
            else:
                lines.append(f"    Given the system is in a valid state")

            action = case.get("action_summary") or case.get("description", "the user performs the action")
            lines.append(f"    When {_sanitize(action)}")

            expected = _sanitize(str(
                case.get("expected_result") or
                case.get("execution", {}).get("expected", "")
            ))
            lines.append(f"    Then {expected}")
            lines.append("")

    return "\n".join(lines)


def render_feature(source: dict) -> str:
    project = source.get("project", "Project")
    scope = source.get("scope", "")
    lines = [
        f"# Generated by gen-gherkin.py from testcase JSON source",
        f"# Project: {project}",
        f"",
        f"Feature: {project}" + (f" — {scope}" if scope else ""),
        f"",
    ]

    errors = []
    for section in source.get("sections", []):
        section_name = _sanitize(section.get("name", ""))
        if section_name:
            lines.append(f"  # === {section_name} ===")
            lines.append("")

        for group in section.get("groups", []):
            group_name = _sanitize(group.get("name", ""))
            if group_name:
                lines.append(f"  # --- {group_name} ---")
                lines.append("")

            for scenario in group.get("scenarios", []):
                errors.extend(validate_scenario(scenario))
                lines.append(render_scenario(scenario))

        # Also handle scenarios directly under section (no group)
        for scenario in section.get("scenarios", []):
            errors.extend(validate_scenario(scenario))
            lines.append(render_scenario(scenario))

    if errors:
        raise ValueError("Validation errors:\n" + "\n".join(f"  - {e}" for e in errors))

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Generate Gherkin .feature file from testcase JSON source"
    )
    parser.add_argument("input", help="Path to testcase JSON source file")
    parser.add_argument("output", help="Output .feature file path")
    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    if not input_path.exists():
        print(f"ERROR: input file not found: {input_path}", file=sys.stderr)
        sys.exit(1)

    source = json.loads(input_path.read_text(encoding="utf-8"))
    try:
        feature_text = render_feature(source)
    except ValueError as err:
        print(f"ERROR: {err}", file=sys.stderr)
        sys.exit(1)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(feature_text, encoding="utf-8")
    print(f"DONE: {output_path}")
    print(f"  sections : {len(source.get('sections', []))}")
    total_scenarios = sum(
        len(g.get("scenarios", [])) + len(s.get("scenarios", []))
        for s in source.get("sections", [])
        for g in s.get("groups", [])
    )
    print(f"  scenarios: {total_scenarios}")


if __name__ == "__main__":
    main()
